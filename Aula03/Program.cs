// Aula 03 - Constantes

namespace Aula03;

public class Program
{
    public static void Main()
    {
        const int idadePaciente = 22;
        // Uma constante não pode ser alterada.
        Console.WriteLine(idadePaciente);


        var nomePaciente = "João";
        // var é uma variável que pode ser alterada.
        Console.WriteLine(nomePaciente);
        // var é uma string só funciona para strings.

    }
}


